const { chromium } = require('playwright');
const fs=require('fs');
(async()=>{const F=12;const b=await chromium.launch();
const p=await b.newPage({viewport:{width:1440,height:900},deviceScaleFactor:2});
await p.goto('file://'+process.cwd()+'/demo-local.html',{waitUntil:'networkidle'});
await p.evaluate(F=>{window.__F=F},F);
const cdp=await p.context().newCDPSession(p); await cdp.send('Animation.enable'); await cdp.send('Animation.setPlaybackRate',{playbackRate:1/F});
await p.waitForTimeout(1500);
fs.mkdirSync('rec',{recursive:true});
const T0=Date.now(); const dt=()=> (Date.now()-T0)/1000/F; // demo seconds
const log=[]; let n=0; let running=true;
const shooter=(async()=>{while(running){const t=dt();await p.screenshot({path:`rec/f${String(n).padStart(4,'0')}.jpg`,type:'jpeg',quality:94});log.push([n,t]);n++;}})();
const waitDemo=async s=>{const end=dt()+s;while(dt()<end)await new Promise(r=>setTimeout(r,50));};
const ev={};
await waitDemo(0.6);
ev.step1=dt(); await p.evaluate(()=>{step1()});
await p.waitForFunction(()=>!document.getElementById('btn2').disabled,null,{timeout:600000});
ev.step1done=dt();
await waitDemo(0.5);
ev.link=await p.evaluate(()=>{const r=document.querySelector('.term-skill-link').getBoundingClientRect();return {x:r.left+r.width/2,y:r.top+r.height/2}});
ev.clickLink=dt(); await p.evaluate(()=>document.querySelector('.term-skill-link').click());
await waitDemo(1.2);
ev.run=await p.evaluate(()=>{const r=document.getElementById('skillRunBtn').getBoundingClientRect();return {x:r.left+r.width/2,y:r.top+r.height/2}});
ev.clickRun=dt(); await p.evaluate(()=>document.getElementById('skillRunBtn').click());
await p.waitForFunction(()=>/Done/.test(document.getElementById('skillRunBtn').innerText),null,{timeout:900000});
ev.done=dt();
await waitDemo(1.5);
running=false; await shooter;
fs.writeFileSync('rec/log.json',JSON.stringify({F,log,ev},null,0));
console.log('frames',n,'demo duration',dt().toFixed(2),JSON.stringify(ev));
await b.close();})();
